import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const appDirectory = join(projectRoot, "src", "app");
const outputFile = join(projectRoot, "src", "lib", "generated-static-sitemap-routes.ts");
const pageFilePattern = /^page\.(?:js|jsx|ts|tsx)$/;
const layoutFileNames = ["layout.js", "layout.jsx", "layout.ts", "layout.tsx"];
const noindexPattern = /robots\s*:\s*\{[^}]*\bindex\s*:\s*false/m;

function findPageFiles(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const entryPath = join(directory, entry.name);
    if (entry.isDirectory()) return findPageFiles(entryPath);
    return pageFilePattern.test(entry.name) ? [entryPath] : [];
  });
}

function routeFromPage(pageFile) {
  const segments = relative(appDirectory, dirname(pageFile)).split(sep);
  const routeSegments = [];

  for (const segment of segments) {
    if (segment === ".") continue;
    if (segment.startsWith("[") || segment.startsWith("_")) return null;
    if (segment.startsWith("(") && segment.endsWith(")")) continue;
    routeSegments.push(segment);
  }

  return routeSegments.length ? `/${routeSegments.join("/")}` : "/";
}

function routeIsNoindex(pageFile) {
  let directory = dirname(pageFile);

  while (directory.startsWith(appDirectory)) {
    const files = directory === dirname(pageFile)
      ? [pageFile, ...layoutFileNames.map((fileName) => join(directory, fileName))]
      : layoutFileNames.map((fileName) => join(directory, fileName));

    if (files.some((file) => existsSync(file) && noindexPattern.test(readFileSync(file, "utf8")))) {
      return true;
    }

    if (directory === appDirectory) break;
    directory = dirname(directory);
  }

  return false;
}

function shouldExclude(route) {
  return route === "/privacy-policy"
    || route === "/search"
    || route.startsWith("/search/")
    || route === "/thank-you"
    || route.startsWith("/thank-you/");
}

const routes = findPageFiles(appDirectory)
  .map((pageFile) => ({ pageFile, route: routeFromPage(pageFile) }))
  .filter(({ route }) => route && !shouldExclude(route))
  .filter(({ pageFile }) => !routeIsNoindex(pageFile))
  .map(({ route }) => route)
  .sort((left, right) => left.localeCompare(right));

const output = `// Generated by scripts/generate-sitemap-static-routes.mjs. Do not edit manually.\nexport const generatedStaticSitemapRoutes = ${JSON.stringify(routes, null, 2)} as const;\n`;

writeFileSync(outputFile, output);
console.log(`Generated ${routes.length} indexable static sitemap routes.`);
